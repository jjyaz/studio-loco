import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
const root = resolve(import.meta.dirname, "..");
const source = readFileSync(resolve(root, "src/lib/continuity.ts"), "utf8");
const contracts = source.slice(
  source.indexOf("export const MAX_STRATEGIES"),
  source.indexOf("/** Checked against"),
);
const bundle = source.slice(
  source.indexOf("export const ContinuityBundle"),
  source.indexOf("/** Imports are labelled"),
);
const stages = source.slice(
  source.indexOf("export type StageStatus"),
  source.indexOf("/** Idempotent by signature"),
);
const prelude = `// Generated by scripts/generate-continuity-contract.mjs from the app's strict contracts.
// No chain reader, transaction builder, signer, device access or execution permission.
import { z } from "zod";
const alphabet = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz";
const isB58Key = (value: unknown): value is string => {
  if (typeof value !== "string" || value.length < 32 || value.length > 44) return false;
  let n = 0n;
  for (const c of value) { const i = alphabet.indexOf(c); if (i < 0) return false; n = n * 58n + BigInt(i); }
  const leading = value.length - value.replace(/^1+/, "").length;
  return leading + (n === 0n ? 0 : Math.ceil(n.toString(16).length / 2)) === 32;
};
export const chapterId = (signature: string, step: number, account: string) => signature + ":" + step + ":" + account;
`;
if (!contracts.includes("StrategySchema") || !bundle.includes("exportContinuity"))
  throw new Error("Continuity contract boundaries changed");
writeFileSync(
  resolve(root, "packages/sdk/src/continuity-schema.ts"),
  (prelude + contracts + bundle + stages).trimEnd() + "\n",
);
